"""把 RBAC 与店铺模块的 tenant 命名统一改为 org。

Revision ID: 0008_tenant_to_org_rename
Revises: 0007_permission_module

历史迁移保留原样，本迁移负责把 0001~0007 产出的 tenant_* 结构升级为当前 ORM 使用的 org_* 结构。
所有语句均为条件执行，可在已经手工执行过 rename_tenant_to_org.sql 的库上重复运行。
"""

from alembic import op


revision = "0008_tenant_to_org_rename"
down_revision = "0007_permission_module"
branch_labels = None
depends_on = None

ORG_TABLES = (
    "biz_department", "biz_department_closure", "biz_department_manager_history",
    "biz_department_shop", "biz_platform_config", "biz_shop",
    "sys_department_permission", "sys_role", "sys_user", "sys_user_role", "sys_user_shop",
)


def _rename_objects(direction: str) -> None:
    """direction=forward: tenant→org；direction=backward: org→tenant。"""
    source, target = ("tenant", "org") if direction == "forward" else ("org", "tenant")

    for table in ORG_TABLES if direction == "forward" else reversed(ORG_TABLES):
        op.execute(f"""DO $$ BEGIN
            IF EXISTS (
                SELECT 1 FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = '{table}' AND column_name = '{source}_id'
            ) THEN
                ALTER TABLE public.{table} RENAME COLUMN {source}_id TO {target}_id;
            END IF;
        END $$""")

    if direction == "forward":
        op.execute("""DO $$ BEGIN
            IF to_regclass('public.sys_tenant') IS NOT NULL AND to_regclass('public.sys_org') IS NULL THEN
                ALTER TABLE public.sys_tenant RENAME TO sys_org;
            END IF;
        END $$""")
    else:
        op.execute("""DO $$ BEGIN
            IF to_regclass('public.sys_org') IS NOT NULL AND to_regclass('public.sys_tenant') IS NULL THEN
                ALTER TABLE public.sys_org RENAME TO sys_tenant;
            END IF;
        END $$""")

    for old_col, new_col in ((f"{source}_code", f"{target}_code"), (f"{source}_name", f"{target}_name")):
        op.execute(f"""DO $$ BEGIN
            IF EXISTS (
                SELECT 1 FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = 'sys_{target}' AND column_name = '{old_col}'
            ) THEN
                ALTER TABLE public.sys_{target} RENAME COLUMN {old_col} TO {new_col};
            END IF;
        END $$""")

    for kind, query, rename_sql in (
        ("constraint",
         "SELECT c.oid, c.conname, c.conrelid::regclass::text AS tbl FROM pg_constraint c "
         "WHERE c.connamespace = 'public'::regnamespace AND c.conname LIKE '%{src}%'",
         "ALTER TABLE {tbl} RENAME CONSTRAINT {old} TO {new}"),
        ("index",
         "SELECT indexname FROM pg_indexes WHERE schemaname = 'public' AND indexname LIKE '%{src}%'",
         "ALTER INDEX public.{old} RENAME TO {new}"),
    ):
        del kind
        rows = op.get_bind().exec_driver_sql(query.format(src=source)).mappings().all()
        for row in rows:
            old_name = row["conname"] if "conname" in row.keys() else row["indexname"]
            new_name = old_name.replace(source, target)
            exists = op.get_bind().exec_driver_sql(
                "SELECT to_regclass('public.' || %s) IS NOT NULL", (new_name,)
            ).scalar() if "indexname" in row.keys() else op.get_bind().exec_driver_sql(
                "SELECT EXISTS (SELECT 1 FROM pg_constraint WHERE connamespace = 'public'::regnamespace AND conname = %s)",
                (new_name,),
            ).scalar()
            if not exists:
                op.execute(rename_sql.format(
                    tbl=row.get("tbl", ""), old=old_name, new=new_name,
                ))


def upgrade() -> None:
    _rename_objects("forward")

    # 权限树已扁平化；负责人改为同组织用户强关联；部门与店铺为多对多。
    op.execute("ALTER TABLE sys_permission DROP COLUMN IF EXISTS parent_id")
    op.execute("ALTER TABLE biz_department ADD COLUMN IF NOT EXISTS manager_id INTEGER REFERENCES sys_user(id)")
    op.execute("CREATE INDEX IF NOT EXISTS ix_biz_department_manager_id ON biz_department(manager_id)")
    op.execute("""DO $$ BEGIN
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_biz_department_manager_user') THEN
            ALTER TABLE biz_department ADD CONSTRAINT fk_biz_department_manager_user
            FOREIGN KEY (org_id, manager_id) REFERENCES sys_user(org_id, id);
        END IF;
    END $$""")
    op.execute("""CREATE TABLE IF NOT EXISTS biz_department_shop (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        org_id INTEGER NOT NULL REFERENCES sys_org(id),
        dept_id INTEGER NOT NULL REFERENCES biz_department(id),
        shop_id INTEGER NOT NULL REFERENCES biz_shop(id),
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        created_by INTEGER, updated_by INTEGER, deleted BOOLEAN NOT NULL DEFAULT FALSE,
        CONSTRAINT uq_dept_shop UNIQUE (org_id, dept_id, shop_id))""")

    # 触发器函数体内的字段同步改名，函数名一并 org 化。
    op.execute("""CREATE OR REPLACE FUNCTION check_department_parent_org() RETURNS trigger AS $$
    BEGIN
        IF NEW.parent_id <> 0 THEN
            IF NEW.parent_id = NEW.id OR NOT EXISTS (
                SELECT 1 FROM biz_department p WHERE p.id = NEW.parent_id
                  AND p.org_id = NEW.org_id AND p.deleted = FALSE
            ) THEN
                RAISE EXCEPTION 'parent department must be active and in the same org';
            END IF;
        END IF;
        RETURN NEW;
    END; $$ LANGUAGE plpgsql""")
    op.execute("DROP TRIGGER IF EXISTS trg_department_parent_org ON biz_department")
    op.execute("""CREATE TRIGGER trg_department_parent_org BEFORE INSERT OR UPDATE OF parent_id, org_id
        ON biz_department FOR EACH ROW EXECUTE FUNCTION check_department_parent_org()""")
    op.execute("DROP TRIGGER IF EXISTS trg_department_parent_tenant ON biz_department")
    op.execute("DROP FUNCTION IF EXISTS check_department_parent_tenant()")


def downgrade() -> None:
    op.execute("DROP TRIGGER IF EXISTS trg_department_parent_org ON biz_department")
    op.execute("DROP FUNCTION IF EXISTS check_department_parent_org()")
    op.execute("DROP TABLE IF EXISTS biz_department_shop")
    op.execute("ALTER TABLE biz_department DROP CONSTRAINT IF EXISTS fk_biz_department_manager_user")
    op.execute("ALTER TABLE biz_department DROP COLUMN IF EXISTS manager_id")
    _rename_objects("backward")
