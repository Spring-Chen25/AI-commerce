def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--seed-test-org", "--seed-test-tenant", dest="seed_test_org", action="store_true",
        help="写入 RBAC_TEST 组织演示数据；旧参数 --seed-test-tenant 兼容保留",
    )
    args = parser.parse_args()
    dsn = os.environ.get("RBAC_DATABASE_URL")
    if not dsn:
        raise SystemExit("请设置 RBAC_DATABASE_URL 后再执行")
    with psycopg.connect(dsn) as conn:
        with conn.cursor() as cur:
            for statement in DDL:
                cur.execute(statement)
        if args.seed_test_org:
            seed(conn)
        with conn.cursor() as cur:
            cur.execute("SELECT COUNT(*) FROM biz_department WHERE id < 1")
            if cur.fetchone()[0]:
                raise RuntimeError("部门表仍存在小于 1 的 ID，已取消提交")
        conn.commit()
        with conn.cursor() as cur:
            cur.execute("SELECT COUNT(*) FROM sys_permission")
            permission_count = cur.fetchone()[0]
            cur.execute("SELECT COUNT(*) FROM sys_role WHERE org_id = (SELECT id FROM sys_org WHERE org_code = 'RBAC_TEST')")
            role_count = cur.fetchone()[0]
            cur.execute("SELECT COUNT(*) FROM sys_role_permission")
            relation_count = cur.fetchone()[0]
    print(f"RBAC schema ready: permissions={permission_count}, roles={role_count}, role_permissions={relation_count}")


if __name__ == "__main__":
    main()
