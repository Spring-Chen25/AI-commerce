def normalize_test_department_ids(conn: psycopg.Connection, org_id: int) -> None:
    """仅对纯演示组织归并部门 ID，并同步迁移全部已知引用。"""
    expected = {code for code, *_ in DEPARTMENTS}
    with conn.cursor() as cur:
        cur.execute("SELECT id, dept_code FROM biz_department WHERE org_id = %s", (org_id,))
        existing = cur.fetchall()
        if {code for _, code in existing} != expected or len(existing) != len(expected):
            # 存在人工创建的部门时，不重排主键，以免误修改用户的真实组织数据。
            return
        by_code = {code: record_id for record_id, code in existing}
        for desired_id, (code, _, parent_code, _, _, _) in enumerate(DEPARTMENTS, start=1):
            old_id = by_code[code]
            if old_id == desired_id:
                continue
            cur.execute("SELECT 1 FROM biz_department WHERE id = %s", (desired_id,))
            if cur.fetchone() is not None:
                raise RuntimeError(f"目标部门 ID {desired_id} 已被占用，停止重排")
            cur.execute(
                "UPDATE biz_department SET dept_code = %s WHERE id = %s",
                (f"{code}_MIGRATING_{old_id}", old_id),
            )
            cur.execute(
                """INSERT INTO biz_department
                (id, org_id, parent_id, dept_name, dept_code, manager_name, phone, email, sort,
                 status, created_at, updated_at, created_by, updated_by, deleted)
                SELECT %s, org_id, parent_id, dept_name, %s, manager_name, phone, email, sort,
                       status, created_at, updated_at, created_by, updated_by, deleted
                FROM biz_department WHERE id = %s""",
                (desired_id, code, old_id),
            )
            cur.execute(
                "UPDATE biz_department SET parent_id = %s WHERE org_id = %s AND parent_id = %s",
                (desired_id, org_id, old_id),
            )
            cur.execute(
                "UPDATE sys_user SET dept_id = %s WHERE org_id = %s AND dept_id = %s",
                (desired_id, org_id, old_id),
            )
            cur.execute(
                "UPDATE biz_shop SET dept_id = %s WHERE org_id = %s AND dept_id = %s",
                (desired_id, org_id, old_id),
            )
            cur.execute(
                "UPDATE sys_department_permission SET dept_id = %s WHERE org_id = %s AND dept_id = %s",
                (desired_id, org_id, old_id),
            )
            cur.execute("DELETE FROM biz_department WHERE id = %s AND org_id = %s", (old_id, org_id))
            by_code[code] = desired_id
        # 新部门的 parent_id 不依赖旧编号；HQ 是唯一的根节点。
        for code, _, parent_code, _, _, _ in DEPARTMENTS:
            cur.execute(
                "UPDATE biz_department SET parent_id = %s WHERE org_id = %s AND dept_code = %s",
                (0 if parent_code is None else by_code[parent_code], org_id, code),
            )
        cur.execute(
            "SELECT setval(pg_get_serial_sequence('biz_department', 'id'), (SELECT MAX(id) FROM biz_department), true)"
        )


